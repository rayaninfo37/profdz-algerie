/**
 * Expand an educational level input/filter string into all known canonical keywords & aliases
 * ensuring high-school, middle-school, primary, and specific exam tracks match cleanly.
 */
export function expandLevelKeywords(level: string | null | undefined): string[] {
  if (!level || !level.trim()) return [];
  const l = level.trim().toLowerCase();

  const keywords: string[] = [level.trim()];

  // Baccalaureate & 3AS
  if (l.includes('bac') || l.includes('بكالوريا') || l.includes('3as')) {
    keywords.push('3AS بكالوريا', 'البكالوريا (BAC)', 'BAC', 'بكالوريا', 'الطور الثانوي', '3AS');
  }
  // Secondary (General)
  if (l.includes('ثانوي') || l.includes('secondary') || l.includes('as')) {
    keywords.push('الطور الثانوي', 'Secondary (الثانوي)', 'ثانوي', '3AS بكالوريا', '2AS', '1AS');
  }
  // 2AS
  if (l.includes('2as') || l.includes('ثانية ثانوي')) {
    keywords.push('2AS', 'السنة الثانية ثانوي', 'الطور الثانوي', 'ثانوي');
  }
  // 1AS
  if (l.includes('1as') || l.includes('أولى ثانوي') || l.includes('جذع مشترك')) {
    keywords.push('1AS', 'السنة الأولى ثانوي', 'الطور الثانوي', 'ثانوي');
  }
  // BEM & Middle school
  if (l.includes('bem') || l.includes('4am') || l.includes('متوسط') || l.includes('middle')) {
    keywords.push('4AM', 'BEM', 'شهادة التعليم المتوسط', 'متوسط', 'الطور المتوسط', 'Middle');
  }
  if (l.includes('3am') || l.includes('ثالثة متوسط')) {
    keywords.push('3AM', 'السنة الثالثة متوسط', 'متوسط', 'الطور المتوسط');
  }
  if (l.includes('2am') || l.includes('ثانية متوسط')) {
    keywords.push('2AM', 'السنة الثانية متوسط', 'متوسط', 'الطور المتوسط');
  }
  if (l.includes('1am') || l.includes('أولى متوسط')) {
    keywords.push('1AM', 'السنة الأولى متوسط', 'متوسط', 'الطور المتوسط');
  }
  // Primary
  if (l.includes('ابتدائي') || l.includes('primary')) {
    keywords.push('ابتدائي', 'Primary', 'التعليم الابتدائي', 'الطور الابتدائي');
  }
  // University
  if (l.includes('جامعي') || l.includes('جامعة') || l.includes('university')) {
    keywords.push('جامعي', 'University', 'التعليم الجامعي', 'جامعة');
  }

  return Array.from(new Set(keywords.filter(Boolean)));
}

